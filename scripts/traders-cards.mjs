// `node scripts/traders-cards.mjs`: writes shared/games/traders/bank.ts from the reviewed card set
// docs/content/traders-cards.csv (id, tier, bonus, points, then the cost in each of the five goods)
// and docs/content/traders-patrons.csv (id, Chinese and English name, then the bonuses wanted). No
// quoting, so no ASCII comma inside a field. The set lives on the server only
// (tests/games/catalog.test.ts); tests/games/traders/bank.test.ts fails if the CSVs and bank.ts drift
// apart, and checks the set's balance. Run from the repo root.
import { readFileSync, writeFileSync } from 'node:fs'

const GOODS = ['tea', 'camphor', 'indigo', 'sugar', 'pepper']
const CARDS = 'docs/content/traders-cards.csv'
const PATRONS = 'docs/content/traders-patrons.csv'
const OUT = 'shared/games/traders/bank.ts'

function read(path, header) {
  const [first, ...lines] = readFileSync(path, 'utf8').replace(/\r/g, '').trim().split('\n')
  if (first !== header) throw new Error(`${path}: unexpected header ${first}`)
  return lines.map((line, index) => {
    const fields = line.split(',').map((field) => field.trim())
    if (fields.length !== header.split(',').length || fields.some((field) => field === '')) {
      throw new Error(`${path}:${index + 2}: expected ${header.split(',').length} non-empty fields`)
    }
    return fields
  })
}

function count(path, field) {
  const value = Number(field)
  if (!Number.isInteger(value) || value < 0) throw new Error(`${path}: ${field} is not a count`)
  return value
}

const cards = read(CARDS, `id,tier,bonus,points,${GOODS.join(',')}`).map(([id, tier, bonus, points, ...cost]) => {
  if (!GOODS.includes(bonus)) throw new Error(`${CARDS}: ${id} has an unknown bonus ${bonus}`)
  return `  { id: '${id}', tier: ${count(CARDS, tier)}, bonus: ${GOODS.indexOf(bonus)}, points: ${count(CARDS, points)}, cost: [${cost.map((value) => count(CARDS, value)).join(', ')}] },`
})

const quote = (field) => `'${field.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
const patrons = read(PATRONS, `id,zh,en,${GOODS.join(',')}`).map(
  ([id, zh, en, ...need]) =>
    `  { id: '${id}', zh: ${quote(zh)}, en: ${quote(en)}, need: [${need.map((value) => count(PATRONS, value)).join(', ')}] },`,
)

writeFileSync(
  OUT,
  `// Generated by scripts/traders-cards.mjs from ${CARDS} and ${PATRONS}: do not edit by hand.
// Server only: shared/games/traders/rules.ts imports it, and the browser imports no rules.
import type { TradersCardRow, TradersPatronRow } from './types.ts'

/** The goods are indexed tea, camphor, indigo, sugar, pepper; \`bonus\` is one of those indexes */
export const TRADERS_CARDS: readonly TradersCardRow[] = [
${cards.join('\n')}
]

export const TRADERS_PATRONS: readonly TradersPatronRow[] = [
${patrons.join('\n')}
]
`,
)
console.log(`${OUT}: ${cards.length} cards, ${patrons.length} patrons`)
