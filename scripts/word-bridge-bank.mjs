// `node scripts/word-bridge-bank.mjs`: writes shared/games/word-bridge/bank.ts from the reviewed
// draft docs/content/word-bridge-words.zh-TW.csv (category, word). No quoting, so no ASCII comma
// inside a field. The bank lives on the server only (tests/games/catalog.test.ts);
// tests/games/word-bridge/bank.test.ts fails if the CSV and bank.ts drift apart. Run from the repo root.
import { readFileSync, writeFileSync } from 'node:fs'

const CSV = 'docs/content/word-bridge-words.zh-TW.csv'
const OUT = 'shared/games/word-bridge/bank.ts'

const [header, ...lines] = readFileSync(CSV, 'utf8').replace(/\r/g, '').trim().split('\n')
if (header !== 'category,word') throw new Error(`${CSV}: unexpected header ${header}`)
const rows = lines.map((line, index) => {
  const fields = line.split(',').map((field) => field.trim())
  if (fields.length !== 2 || fields.some((field) => field === '')) {
    throw new Error(`${CSV}:${index + 2}: expected two non-empty fields`)
  }
  return fields
})

const quote = (field) => `'${field.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
writeFileSync(
  OUT,
  `// Generated by scripts/word-bridge-bank.mjs from ${CSV}: do not edit by hand.
// Server only: shared/games/word-bridge/rules.ts imports it, and the browser imports no rules.

/** category and word, in the CSV's order */
export const WB_WORDS: readonly (readonly [string, string])[] = [
${rows.map((row) => `  [${row.map(quote).join(', ')}],`).join('\n')}
]
`,
)
console.log(`${OUT}: ${rows.length} words`)
