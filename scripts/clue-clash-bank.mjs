// `node scripts/clue-clash-bank.mjs`: writes shared/games/clue-clash/bank.ts from the reviewed
// draft docs/content/clue-clash-words.zh-TW.csv (category, word, other answers that count with
// `/` between them, or empty). No quoting, so no ASCII comma
// inside a field. The bank lives on the server only (tests/games/catalog.test.ts);
// tests/games/clue-clash/bank.test.ts fails if the CSV and bank.ts drift apart. Run from the repo root.
import { readFileSync, writeFileSync } from 'node:fs'

const CSV = 'docs/content/clue-clash-words.zh-TW.csv'
const OUT = 'shared/games/clue-clash/bank.ts'

const [header, ...lines] = readFileSync(CSV, 'utf8').replace(/\r/g, '').trim().split('\n')
if (header !== 'category,word,alts') throw new Error(`${CSV}: unexpected header ${header}`)
const rows = lines.map((line, index) => {
  const fields = line.split(',').map((field) => field.trim())
  if (fields.length !== 3 || fields[0] === '' || fields[1] === '') {
    throw new Error(`${CSV}:${index + 2}: expected category, word and (maybe empty) alts`)
  }
  return fields
})

const quote = (field) => `'${field.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
writeFileSync(
  OUT,
  `// Generated by scripts/clue-clash-bank.mjs from ${CSV}: do not edit by hand.
// Server only: shared/games/clue-clash/rules.ts imports it, and the browser imports no rules.

import type { CcWordRow } from './types.ts'

/** category, word, other answers (\`/\` between them); a word's id is its index here plus one */
export const CC_WORDS: readonly CcWordRow[] = [
${rows.map((row) => `  [${row.map(quote).join(', ')}],`).join('\n')}
]
`,
)
console.log(`${OUT}: ${rows.length} words`)
