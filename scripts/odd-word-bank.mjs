// `node scripts/odd-word-bank.mjs`: writes shared/games/odd-word/bank.ts from the reviewed draft
// docs/content/odd-word-pairs.zh-TW.csv (category, first, second: the two words of a pair, in no
// order). No quoting, so no ASCII comma inside a field. The bank lives on the server only
// (tests/games/catalog.test.ts); tests/games/odd-word/bank.test.ts fails if the CSV and bank.ts drift
// apart. Run from the repo root.
import { readFileSync, writeFileSync } from 'node:fs'

const CSV = 'docs/content/odd-word-pairs.zh-TW.csv'
const OUT = 'shared/games/odd-word/bank.ts'

const [header, ...lines] = readFileSync(CSV, 'utf8').replace(/\r/g, '').trim().split('\n')
if (header !== 'category,first,second') throw new Error(`${CSV}: unexpected header ${header}`)
const rows = lines.map((line, index) => {
  const fields = line.split(',').map((field) => field.trim())
  if (fields.length !== 3 || fields.some((field) => field === '')) {
    throw new Error(`${CSV}:${index + 2}: expected three non-empty fields`)
  }
  return fields
})

const quote = (field) => `'${field.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
writeFileSync(
  OUT,
  `// Generated by scripts/odd-word-bank.mjs from ${CSV}: do not edit by hand.
// Server only: shared/games/odd-word/rules.ts imports it, and the browser imports no rules.
import type { OddPairRow } from './types.ts'

/** category and the two words; a pair's id is its index here plus one */
export const ODD_PAIRS: readonly OddPairRow[] = [
${rows.map((row) => `  [${row.map(quote).join(', ')}],`).join('\n')}
]
`,
)
console.log(`${OUT}: ${rows.length} pairs`)
