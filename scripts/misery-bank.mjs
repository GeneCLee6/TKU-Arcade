// `node scripts/misery-bank.mjs`: writes shared/games/misery/bank.ts from the reviewed draft
// docs/content/misery-cards.zh-TW.csv (category, title, index: one miserable event and how bad it is,
// from 1 to 100). No quoting, so no ASCII comma inside a field. The bank lives on the server only
// (tests/games/catalog.test.ts); tests/games/misery/bank.test.ts fails if the CSV and bank.ts drift
// apart. Run from the repo root.
import { readFileSync, writeFileSync } from 'node:fs'

const CSV = 'docs/content/misery-cards.zh-TW.csv'
const OUT = 'shared/games/misery/bank.ts'

const [header, ...lines] = readFileSync(CSV, 'utf8').replace(/\r/g, '').trim().split('\n')
if (header !== 'category,title,index') throw new Error(`${CSV}: unexpected header ${header}`)
const rows = lines.map((line, index) => {
  const fields = line.split(',').map((field) => field.trim())
  const misery = Number(fields[2])
  if (fields.length !== 3 || fields.some((field) => field === '')) {
    throw new Error(`${CSV}:${index + 2}: expected three non-empty fields`)
  }
  if (!Number.isInteger(misery) || misery < 1 || misery > 100) {
    throw new Error(`${CSV}:${index + 2}: the index must be a whole number from 1 to 100`)
  }
  return [fields[0], fields[1], misery]
})

const quote = (field) => `'${field.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
writeFileSync(
  OUT,
  `// Generated by scripts/misery-bank.mjs from ${CSV}: do not edit by hand.
// Server only: shared/games/misery/rules.ts imports it, and the browser imports no rules.
import type { MiseryCardRow } from './types.ts'

/** category, title and misery index; a card's id is its index here plus one */
export const MISERY_CARDS: readonly MiseryCardRow[] = [
${rows.map(([category, title, misery]) => `  [${quote(category)}, ${quote(title)}, ${misery}],`).join('\n')}
]
`,
)
console.log(`${OUT}: ${rows.length} cards`)
